import { describe, expect, it } from "vitest";
import { extractPdfText } from "@/lib/pdf/document";
import { renderQuotePdf, WATERMARK } from "./pdf";
import type { QuoteDetailDto } from "./schema";

const quote = (over: Partial<QuoteDetailDto> = {}): QuoteDetailDto =>
  ({
    id: "q1",
    quoteNumber: "Q-000123",
    customerId: "c1",
    customerName: "Acme Plumbing",
    title: "Rooftop unit replacement",
    status: "sent",
    issueDate: "2026-10-15",
    validUntil: "2026-11-15",
    taxRateBps: 825,
    discountCents: 10000,
    subtotalCents: 942675,
    taxCents: 76946,
    totalCents: 1009621,
    notes: "Net 30.\nThanks for your business.",
    items: [
      {
        id: "i1",
        position: 1,
        description: "Rooftop unit, 10 ton",
        quantity: 1,
        unitPriceCents: 845000,
        lineTotalCents: 845000,
      },
      {
        id: "i2",
        position: 2,
        description: "Crane rental, per hour",
        quantity: 3,
        unitPriceCents: 32550,
        lineTotalCents: 97650,
      },
      {
        id: "i3",
        position: 3,
        description: "Disposal of old unit",
        quantity: 1,
        unitPriceCents: 25,
        lineTotalCents: 25,
      },
    ],
    revises: null,
    revisions: [],
    statusHistory: [],
    ...over,
  }) as QuoteDetailDto;
const text = (bytes: Uint8Array) => extractPdfText(bytes).join("\n");

describe("renderQuotePdf", () => {
  const real = renderQuotePdf(quote(), { demo: false, organizationName: "Acme Heating" });

  it("is a PDF with the quote's number, status, customer, dates and workspace", () => {
    expect(Buffer.from(real.slice(0, 8)).toString()).toBe("%PDF-1.4");
    const t = text(real);
    for (const needle of [
      "OpsDesk",
      "QUOTE",
      "Q-000123",
      "Rooftop unit replacement",
      "Acme Heating",
      "Acme Plumbing",
      "Sent",
      "Oct 15, 2026",
      "Nov 15, 2026",
    ])
      expect(t).toContain(needle);
  });
  it("lists every line with quantity, unit price and line total", () => {
    const t = text(real);
    for (const needle of [
      "Rooftop unit, 10 ton",
      "$8,450.00",
      "Crane rental, per hour",
      "$325.50",
      "$976.50",
      "$0.25",
    ])
      expect(t).toContain(needle);
  });
  it("shows the stored subtotal, discount, tax with its rate, and total", () => {
    const t = text(real);
    for (const needle of [
      "Subtotal",
      "$9,426.75",
      "Discount",
      "-$100.00",
      "Tax (8.25%)",
      "$769.46",
      "Total",
      "$10,096.21",
    ])
      expect(t).toContain(needle);
  });
  it("includes notes and a footer with page numbers", () => {
    const t = text(real);
    expect(t).toContain("Notes");
    expect(t).toContain("Net 30.");
    expect(t).toContain("Thanks for your business.");
    expect(t).toContain("Page 1 of 1");
    expect(t).toContain("Generated by OpsDesk");
  });
  it("omits the discount row when there is no discount, and says 'No end date' without one", () => {
    const t = text(
      renderQuotePdf(
        quote({
          discountCents: 0,
          validUntil: null,
          notes: null,
          subtotalCents: 942675,
          taxCents: 77771,
          totalCents: 1020446,
        }),
        { demo: false, organizationName: "X Co" },
      ),
    );
    expect(t).not.toContain("Discount");
    expect(t).toContain("No end date");
    expect(t).not.toContain("Notes");
  });
  it("a real workspace has no watermark; a demo has it on every page", () => {
    expect(text(real)).not.toContain(WATERMARK);
    const many = quote({
      items: Array.from({ length: 70 }, (_, i) => ({
        id: `i${i}`,
        position: i + 1,
        description: `Line item number ${i + 1} with a reasonably long description so that it wraps onto a second line in the table`,
        quantity: 1,
        unitPriceCents: 100,
        lineTotalCents: 100,
      })),
    });
    const demo = extractPdfText(renderQuotePdf(many, { demo: true, organizationName: "Demo Co" }));
    expect(demo.length).toBeGreaterThan(1);
    demo.forEach((page, i) => {
      expect(page).toContain(WATERMARK);
      expect(page).toContain(`Page ${i + 1} of ${demo.length}`);
      expect(page).toContain("Q-000123");
    });
    const realMany = extractPdfText(
      renderQuotePdf(many, { demo: false, organizationName: "Real Co" }),
    );
    expect(realMany.some((p) => p.includes(WATERMARK))).toBe(false);
    expect(realMany.join("\n")).toContain("Line item number 70");
  });
  it("repeats the table header on later pages and keeps the totals after the last line", () => {
    const many = quote({
      items: Array.from({ length: 60 }, (_, i) => ({
        id: `i${i}`,
        position: i + 1,
        description: `Item ${i + 1}`,
        quantity: 1,
        unitPriceCents: 100,
        lineTotalCents: 100,
      })),
    });
    const pages = extractPdfText(renderQuotePdf(many, { demo: false, organizationName: "Co" }));
    expect(pages.length).toBeGreaterThan(1);
    pages.forEach((p) => expect(p).toContain("Description"));
    expect(pages.at(-1)).toContain("$10,096.21");
  });
  it("is deterministic and escapes hostile text", () => {
    const hostile = quote({
      title: "Evil ) Tj ET (injected) \\",
      customerName: "A (b) c",
      notes: "<script>alert(1)</script> ‮ rtl",
    });
    const a = renderQuotePdf(hostile, { demo: false, organizationName: "O)rg" });
    const b = renderQuotePdf(hostile, { demo: false, organizationName: "O)rg" });
    expect(Buffer.from(a).equals(Buffer.from(b))).toBe(true);
    const t = text(a);
    expect(t).toContain("Evil ) Tj ET (injected) \\");
    expect(t).toContain("A (b) c");
    expect(Buffer.from(a).toString("latin1")).not.toContain("‮");
  });
});
